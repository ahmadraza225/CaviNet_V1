"""docs/EVALUATION_REPORT.md (section 11.7): the cross-validation results and, once run, the
locked test set, with the hypotheses (H1, H2) stated as supported or not supported."""

import os
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from cavinet_ml import __version__
from cavinet_ml.provenance import git_commit

METRIC_NAMES = (
    ("auc", "AUC", False),
    ("sensitivity", "Sensitivity (TB)", True),
    ("specificity", "Specificity (NTM)", True),
    ("ppv", "PPV", True),
    ("npv", "NPV", True),
    ("accuracy", "Accuracy", True),
    ("balanced_accuracy", "Balanced accuracy", True),
    ("f1", "F1", False),
    ("brier", "Brier score", False),
    ("ece", "Expected calibration error", False),
)


def _num(value: Any, digits: int = 3) -> str:
    if value is None or (isinstance(value, float) and value != value):
        return "—"
    return f"{float(value):.{digits}f}"


def _pct(value: Any) -> str:
    if value is None or (isinstance(value, float) and value != value):
        return "—"
    return f"{100 * float(value):.1f}%"


def _with_ci(value: Any, ci: Any, pct: bool = False) -> str:
    fmt = _pct if pct else _num
    if not ci:
        return fmt(value)
    return f"{fmt(value)} ({fmt(ci[0])} to {fmt(ci[1])})"


def _figure(report: Path, figure: str | None, caption: str) -> list[str]:
    if not figure:
        return []
    relative = os.path.relpath(figure, report.parent)
    return [f"![{caption}]({Path(relative).as_posix()})", ""]


def _verdict(supported: bool) -> str:
    return "**Supported**" if supported else "**Not supported**"


def _counts_line(name: str, counts: dict[str, Any]) -> str:
    tb, ntm = counts.get("tb", "—"), counts.get("ntm", "—")
    return f"{counts.get('n', '—')} patients ({tb} TB, {ntm} NTM)"


def _comparison(comp: dict[str, Any]) -> str:
    if not comp.get("ci"):
        return f"{comp['difference']:+.3f} (no CI: {comp.get('note', 'not computable')})"
    low, high = comp["ci"]
    return f"{comp['difference']:+.3f} (95% CI {low:+.3f} to {high:+.3f})"


def _p(comp: dict[str, Any]) -> str:
    return "—" if comp.get("p_value") is None else f"{comp['p_value']:.4f}"


def render(
    report: Path, *, data: dict[str, Any], dev: dict[str, Any], test: dict[str, Any] | None
) -> str:
    counts = data.get("counts", {})
    cal = dev["calibration"]
    oof = cal["oof"]
    now = datetime.now(UTC).isoformat(timespec="seconds")
    lines = [
        "# CaviNet evaluation report",
        "",
        f"> Generated by `cavinet-ml evaluate` on {now} (toolkit {__version__}, "
        f"git `{git_commit()}`). Do not edit by hand.",
        "",
    ]
    if data.get("synthetic") or (test and test["bundle"]["is_demo"]):
        lines += [
            "> **SYNTHETIC REHEARSAL: NOT A RESULT.** These numbers come from the synthetic "
            "look-alike dataset and a demo model. They say nothing about TB or NTM.",
            "",
        ]
    lines += ["## Summary", "", "| Question | Result |", "|---|---|"]
    if test:
        h1, h2 = test["hypotheses"]["H1"], test["hypotheses"]["H2"]
        shortcut = test["baselines"]["metadata"]["interpretation"]
        lines += [
            "| H1: the CT model separates TB from NTM better than chance | "
            f"{_verdict(h1['supported'])}. {h1['statement']} |",
            "| H2: CT adds information beyond demographics and symptoms | "
            f"{_verdict(h2['supported'])}. {h2['statement']} |",
            f"| Shortcut check (locked test set) | {shortcut} |",
        ]
    else:
        lines += [
            "| H1, H2 | Not tested yet: the locked test set has not been evaluated "
            "(`cavinet-ml evaluate --split test`, once, after the model is frozen). |",
        ]
    folds = ", ".join(str(f["n"]) for f in counts.get("folds", []))
    strata = " × ".join(data.get("stratify_by", []))
    lines += [
        "| Cross-validation (development set) | Pooled out-of-fold AUC "
        f"{_with_ci(oof['auc'], oof.get('auc_ci'))} on {cal['n']} patients. |",
        "",
        "## Data",
        "",
        f"- Patients in the manifest: {counts.get('patients', '—')}; excluded before "
        f"splitting: {counts.get('excluded', '—')}.",
        f"- Development set: {_counts_line('dev', counts.get('dev', {}))} in "
        f"{data.get('n_folds')} folds of {folds}.",
        f"- Locked test set: {_counts_line('test', counts.get('test', {}))}, "
        f"{_pct(data.get('test_fraction'))} of the usable patients, stratified by {strata}, "
        f"seed {data.get('seed')}.",
    ]
    if data.get("excluded"):
        lines += ["", "Excluded patients:", "", "| Patient | Reason |", "|---|---|"]
        lines += [f"| {case_id} | {reason} |" for case_id, reason in data["excluded"].items()]
    lines += [
        "",
        "## Cross-validation (development set)",
        "",
        "| Fold | Patients | Out-of-fold AUC |",
        "|---|---|---|",
    ]
    lines += [f"| {f['fold']} | {f['n']} | {_num(f['auc'])} |" for f in dev["folds"]]
    lines += [
        "",
        f"- Pooled out-of-fold AUC: {_with_ci(oof['auc'], oof.get('auc_ci'))}.",
        f"- Calibration (temperature scaling, T = {_num(cal['temperature'], 4)}): expected "
        f"calibration error {_num(oof['ece_before'])} before, {_num(oof['ece'])} after; Brier "
        f"score {_num(oof['brier_before'])} before, {_num(oof['brier'])} after.",
        "- Youden-optimal threshold on the development set: "
        f"{_num(cal['youden_threshold'])} (reported for reference; the application uses 0.50).",
    ]
    for kind, summary in dev.get("baselines", {}).items():
        comparison = dev["comparisons"].get(kind)
        auc = _with_ci(summary["auc"], summary["auc_ci"])
        text = f"- {summary['description']}: out-of-fold AUC {auc}"
        if comparison:
            text += f"; CT minus this model {_comparison(comparison)}, DeLong p = {_p(comparison)}."
        lines.append(text if comparison else text + ".")
        if summary.get("interpretation"):
            lines.append(f"  {summary['interpretation']}")
    lines.append("")
    figs = dev.get("figures", {})
    lines += _figure(report, figs.get("training_curves"), "Training curves")
    lines += _figure(report, figs.get("roc_dev"), "ROC curves, development set")
    lines += _figure(report, figs.get("reliability_dev"), "Reliability diagram, development set")

    lines += ["## Locked test set", ""]
    if not test:
        lines += [
            "Not evaluated yet. Run `cavinet-ml evaluate --split test` exactly once, after the "
            "model is frozen (exported).",
            "",
        ]
        lines += _methods()
        return "\n".join(lines)
    ct = test["ct"]
    m = ct["metrics"]
    bundle = test["bundle"]
    forced = f", forced: {test['reason']}" if test["forced"] else ""
    lines += [
        f"Evaluated on {test['evaluated_at']} (run {test['run']}{forced}) with "
        f"`{Path(bundle['file']).name}` ({bundle['model_name']}, version "
        f"{bundle['model_version']}, trained {bundle['created_at']}); file SHA-256 "
        f"`{bundle['sha256']}`, weights SHA-256 `{bundle['weights_sha256']}`.",
        "",
        f"{test['n']} patients ({test['n_tb']} TB, {test['n_ntm']} NTM). Threshold 0.50 "
        "(the application's).",
        "",
        "| Metric | Value (95% CI) |",
        "|---|---|",
    ]
    lines += [
        f"| {label} | {_with_ci(m[key]['value'], m[key]['ci'], pct)} |"
        for key, label, pct in METRIC_NAMES
    ]
    delong = ct["auc_delong"]
    c = ct["confusion"]
    y = ct["at_youden"]

    def at_youden(name: str) -> str:
        return _with_ci(y[name]["value"], y[name]["ci"], True)

    lines += [
        "",
        "AUC 95% CI by DeLong's method, for reference: "
        + (
            f"{_num(delong['ci'][0])} to {_num(delong['ci'][1])}."
            if delong.get("ci")
            else f"not computable ({delong.get('note')})."
        ),
        "",
        "| | Predicted TB | Predicted NTM |",
        "|---|---|---|",
        f"| Actual TB | {c['tp']} | {c['fn']} |",
        f"| Actual NTM | {c['fp']} | {c['tn']} |",
        "",
        "At the Youden-optimal threshold chosen on the development set "
        f"({_num(ct['youden_threshold'])}): sensitivity {at_youden('sensitivity')}, "
        f"specificity {at_youden('specificity')}, balanced accuracy "
        f"{at_youden('balanced_accuracy')}.",
        "",
        "### Clinical-only baseline and shortcut check",
        "",
        "Both models were fitted on the whole development set and applied once to the same "
        "test patients.",
        "",
        "| Model | Test AUC (95% CI) | CT minus model (95% CI) | DeLong p |",
        "|---|---|---|---|",
    ]
    for summary in test["baselines"].values():
        comp = summary["comparison_with_ct"]
        auc = _with_ci(summary["auc"], summary["auc_ci"])
        lines.append(f"| {summary['description']} | {auc} | {_comparison(comp)} | {_p(comp)} |")
    lines += ["", test["baselines"]["metadata"]["interpretation"], "", "### Subgroups", ""]
    lines += ["| Subgroup | Patients (TB / NTM) | AUC (95% CI) |", "|---|---|---|"]
    for row in test["subgroups"]:
        auc = (
            _with_ci(row["auc"], row["auc_ci"]) if row["auc"] is not None else row.get("note", "—")
        )
        patients = f"{row['n']} ({row['n_tb']} / {row['n_ntm']})"
        lines.append(f"| {row['group']}: {row['value']} | {patients} | {auc} |")
    lines.append("")
    figs = test.get("figures", {})
    lines += _figure(report, figs.get("roc_test"), "ROC curves, locked test set")
    lines += _figure(report, figs.get("reliability_test"), "Reliability diagram, locked test set")
    lines += _figure(report, figs.get("confusion_test"), "Confusion matrix, locked test set")
    lines += _figure(report, figs.get("scores_test"), "Predicted probabilities, locked test set")
    lines += _figure(report, figs.get("subgroups_test"), "Subgroup AUCs, locked test set")
    lines += _methods()
    return "\n".join(lines)


def _methods() -> list[str]:
    return [
        "## Methods",
        "",
        "- Confidence intervals: stratified bootstrap (TB and NTM resampled separately), 2,000 "
        "resamples, seed 42, percentile 95% intervals; every metric uses the same resamples.",
        "- AUC comparisons: DeLong's test for correlated ROC curves on the same patients (fast "
        "midrank algorithm).",
        "- Expected calibration error: 10 equal-width bins of the predicted probability of TB.",
        "- Baselines: logistic regression with class weighting; missing values imputed from the "
        "training part only.",
        "- The locked test set is used once: every run is logged in "
        "docs/audit/evaluation_runs.jsonl.",
        "",
    ]


def write_report(
    path: Path, *, data: dict[str, Any], dev: dict[str, Any], test: dict[str, Any] | None
) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(path, data=data, dev=dev, test=test))
    return path
